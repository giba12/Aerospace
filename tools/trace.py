#!/usr/bin/env python3
"""Requirements traceability: tests -> requirement IDs, and the CI gate (TST-011, SYS-005).

Inputs
  --requirements  docs/requirements.csv (the registry of valid IDs and priorities)
  --junit         JUnit XML files. A test names the requirements it verifies with a property
                  called "requirements" holding comma-separated IDs. GoogleTest writes it as an
                  attribute of <testcase> (RecordProperty); pytest writes a <property> child
                  (@pytest.mark.req, see tests/conftest.py).

Checks (each failure makes the exit code 1)
  1. A test cites an ID that is not in the registry.
  2. A test cites no requirement at all (TST-005).
  3. With --require-coverage only: a Must requirement has no passing test.

Check 3 is a report until the gate is switched on in M5 (baseline 6.7); the coverage gap list
is still printed every run so progress is visible.
"""
import argparse
import csv
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict


def load_registry(path):
    """Return {id: priority}. Lines starting with '#' are comments."""
    with open(path, newline="", encoding="utf-8") as f:
        lines = [ln for ln in f if not ln.lstrip().startswith("#")]
    return {row["id"]: row["priority"] for row in csv.DictReader(lines)}


def _split_ids(text):
    return [t.strip() for t in text.replace(";", ",").split(",") if t.strip()]


def load_tests(junit_paths):
    """Return a list of (test_name, [requirement ids], passed) from JUnit files."""
    tests = []
    for path in junit_paths:
        for case in ET.parse(path).getroot().iter("testcase"):
            ids = _split_ids(case.get("requirements", ""))
            for prop in case.iter("property"):
                if prop.get("name") == "requirements":
                    ids += _split_ids(prop.get("value", ""))
            failed = any(case.find(tag) is not None for tag in ("failure", "error", "skipped"))
            name = f"{case.get('classname', '')}.{case.get('name', '')}".strip(".")
            tests.append((name, ids, not failed))
    return tests


def analyze(registry, tests):
    """Return (errors, coverage) where coverage maps requirement id -> list of passing tests."""
    errors = []
    coverage = defaultdict(list)
    for name, ids, passed in tests:
        if not ids:
            errors.append(f"orphan test (cites no requirement): {name}")
        for rid in ids:
            if rid not in registry:
                errors.append(f"unknown requirement {rid} cited by {name}")
            elif passed:
                coverage[rid].append(name)
    return errors, coverage


def write_matrix(path, registry, coverage):
    with open(path, "w", encoding="utf-8") as f:
        f.write("# Requirements traceability matrix (generated by tools/trace.py)\n\n")
        f.write("| ID | Pri | Passing tests |\n|---|---|---|\n")
        for rid, pri in registry.items():
            names = "<br>".join(coverage.get(rid, [])) or "**none**"
            f.write(f"| {rid} | {pri} | {names} |\n")


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--requirements", required=True)
    p.add_argument("--junit", required=True, nargs="+")
    p.add_argument("--matrix-out", help="write the matrix as Markdown to this path")
    p.add_argument("--require-coverage", action="store_true",
                   help="fail if any Must requirement has no passing test (gate on in M5)")
    args = p.parse_args(argv)

    registry = load_registry(args.requirements)
    errors, coverage = analyze(registry, load_tests(args.junit))

    musts = [r for r, pri in registry.items() if pri == "M"]
    gaps = [r for r in musts if r not in coverage]
    print(f"trace: {len(musts) - len(gaps)}/{len(musts)} Must requirements have a passing test")
    if gaps:
        print("trace: Must requirements without a passing test: " + ", ".join(gaps))
        if args.require_coverage:
            errors.append(f"{len(gaps)} Must requirement(s) have no passing test")
    if args.matrix_out:
        write_matrix(args.matrix_out, registry, coverage)
    for e in errors:
        print(f"trace: error: {e}", file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
